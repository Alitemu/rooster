const args = process.argv.slice(2);
const sindsAt = args.indexOf('--sinds');
const sinds = sindsAt >= 0 ? args[sindsAt + 1] : null;
if (sindsAt >= 0 && !sinds) {
  console.error('--sinds needs a git ref, such as v0.81.0');
  process.exit(2);
}
const droog = args.includes('--droog');
const only = args.filter((a, i) => a !== '--droog' && (sindsAt < 0 || (i !== sindsAt && i !== sindsAt + 1)))[0];
let changed = null;
if (sinds) {
  const diff = spawnSync('git', ['diff', '--name-only', sinds], { cwd: repoRoot, encoding: 'utf8' });
  if (diff.status !== 0) {
    console.error(`git diff ${sinds} failed: ${diff.stderr}`);
    process.exit(2);
  }
  changed = diff.stdout.split('\n').filter(Boolean);
}
// A vitest filter is a path prefix; a pytest one names a file in the solver's folder.
const testPaths = (m) =>
  m.runner === 'pytest' ? m.tests.filter((t) => t.endsWith('.py')).map((t) => path.posix.join(m.cwd ?? 'solver', t)) : m.tests;
const touched = (m) => changed.includes(m.file) || testPaths(m).some((t) => changed.some((c) => c.startsWith(t)));
const chosen = MUTATIONS.filter((m) => (!only || m.name.includes(only)) && (!changed || touched(m)));
if (changed) console.log(`${MUTATIONS.filter(touched).length} of ${MUTATIONS.length} mutations: their file or a test of theirs changed since ${sinds}\n`);
const originals = new Map();
// A copy of a file next to the run, taken before it is mutated: SIGKILL, an out-of-memory kill or a crash of the
// machine cannot be caught, and left the mutated source in the tree (found in the audit of 0.112.0, for SIGTERM).
// The next run puts the files back first.
const backupDir = path.join(repoRoot, '.mutation-backup');
const backupNaam = (file) => path.join(backupDir, encodeURIComponent(path.relative(repoRoot, file)));
function herstelAfgebroken() {
  if (!fs.existsSync(backupDir)) return 0;
  let n = 0;
  for (const naam of fs.readdirSync(backupDir)) {
    fs.writeFileSync(path.join(repoRoot, decodeURIComponent(naam)), fs.readFileSync(path.join(backupDir, naam)));
    n++;
  }
  fs.rmSync(backupDir, { recursive: true, force: true });
  return n;
}
const restoreAll = () => {
  for (const [file, src] of originals) fs.writeFileSync(file, src);
  originals.clear();
  fs.rmSync(backupDir, { recursive: true, force: true });
};
// Every way a process is asked to stop or stops on its own: the source is put back before it goes.
for (const [signaal, code] of [['SIGINT', 130], ['SIGTERM', 143], ['SIGHUP', 129]]) {
  process.on(signaal, () => {
    restoreAll();
    process.exit(code);
  });
}
process.on('uncaughtException', (error) => {
  restoreAll();
  console.error(error);
  process.exit(1);
});
process.on('exit', restoreAll);
if (!droog) {
  const hersteld = herstelAfgebroken();
  if (hersteld) console.log(`Een eerdere run was afgebroken: ${hersteld} bestand(en) teruggezet voor deze begint.\n`);
}

// --droog: no test runs; only whether every `find` is still in its file, once (or says alles: true). Fast.
if (droog) {
  const slecht = [];
  const bestanden = spawnSync('git', ['ls-files'], { cwd: repoRoot, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).stdout.split('\n');
  for (const m of MUTATIONS) {
    const bron = fs.readFileSync(path.join(repoRoot, m.file), 'utf8');
    const n = bron.split(m.find).length - 1;
    if (n === 0) slecht.push(`${m.name} (niet gevonden)`);
    else if (n > 1 && !m.alles) slecht.push(`${m.name} (${n} keer gevonden)`);
    // A test filter that matches no file runs nothing: the other filters may still carry the mutation, but the
    // entry is dead weight that hides the day the last live one goes.
    for (const t of m.runner === 'pytest' ? m.tests.filter((x) => x.endsWith('.py')).map((x) => path.posix.join(m.cwd ?? 'solver', x)) : m.tests) {
      if (!bestanden.some((f) => f.includes(t))) slecht.push(`${m.name} (testfilter ${t} past op geen bestand)`);
    }
  }
  console.log(`${MUTATIONS.length} mutaties, ${slecht.length} met een find die niet klopt`);
  for (const s of slecht) console.log(`  - ${s}`);
  process.exit(slecht.length ? 1 : 0);
}

const survived = [];
for (const m of chosen) {
  const file = path.join(repoRoot, m.file);
  const src = fs.readFileSync(file, 'utf8');
  if (!src.includes(m.find)) {
    console.log(`? ${m.name} - the code it breaks is gone, update this mutation`);
    survived.push(`${m.name} (niet gevonden)`);
    continue;
  }
  // A find that occurs twice mutated only the first: the other handler or call stayed unguarded, unseen.
  // Either make it unique or say `alles: true` (every occurrence, which a guard test must catch too).
  const keer = src.split(m.find).length - 1;
  if (keer > 1 && !m.alles) {
    console.log(`? ${m.name} - the find text occurs ${keer} times, make it unique or say alles: true`);
    survived.push(`${m.name} (${keer} keer gevonden)`);
    continue;
  }
  originals.set(file, src);
  fs.mkdirSync(backupDir, { recursive: true });
  fs.writeFileSync(backupNaam(file), src);
  try {
    fs.writeFileSync(file, m.alles ? src.split(m.find).join(m.replace) : src.replace(m.find, () => m.replace));
    // A solver mutation runs the solver's own tests (pytest in ./solver,
    // SOLVER_PYTHON or python3 with OR-Tools and pytest installed).
    const pytest = m.runner === 'pytest';
    const run = pytest
      ? spawnSync(process.env.SOLVER_PYTHON || 'python3', ['-m', 'pytest', '-q', '-p', 'no:cacheprovider', ...m.tests], {
          cwd: path.join(repoRoot, m.cwd ?? 'solver'),
          encoding: 'utf8',
          timeout: 15 * 60 * 1000,
        })
      : spawnSync('npx', ['vitest', 'run', ...m.tests], { cwd: repoRoot, encoding: 'utf8', timeout: 15 * 60 * 1000 });
    const output = `${run.stdout ?? ''}${run.stderr ?? ''}`;
    // A filter that matches nothing fails too: that is a broken mutation,
    // not a caught one. So is a Python without pytest or OR-Tools.
    if (
      /No test files found/.test(output) ||
      (pytest && (run.error || run.status === 5 || /No module named|ModuleNotFoundError/.test(output)))
    ) {
      console.log(`? ${m.name} - no tests ran for ${m.tests.join(' ')}`);
      survived.push(`${m.name} (geen tests gevonden)`);
      continue;
    }
    const summary = (
      (pytest ? output.match(/^.*\b(failed|passed)\b.* in [\d.]+s.*$/m) : run.stdout.match(/Tests\s+.*$/m)) || ['(no summary)']
    )[0].trim();
    // Caught means a TEST failed. A timeout (status null), a mutation that breaks loading (a syntax or import
    // error fails the suite without one failing test) or a crash of the runner is a broken mutation, not a catch.
    const eenTestFaalde = /\bfailed\b/.test(summary) && !/Failed to load|SyntaxError|Cannot find module|ERR_MODULE_NOT_FOUND/.test(summary);
    const caught = typeof run.status === 'number' && run.status !== 0 && !run.signal && eenTestFaalde;
    if (!caught && typeof run.status === 'number' && run.status !== 0) {
      console.log(`? ${m.name} - the run failed, but no test did (${summary}): a broken mutation or a runner problem`);
      survived.push(`${m.name} (geen falende test)`);
      continue;
    }
    if (run.status === null) {
      console.log(`? ${m.name} - the run did not finish (timeout or signal)`);
      survived.push(`${m.name} (niet afgerond)`);
      continue;
    }
    console.log(`${caught ? '✓ gevangen ' : '✗ OVERLEEFT'}  ${m.name}  [${summary}]`);
    if (!caught) survived.push(m.name);
  } finally {
    restoreAll();
  }
}

console.log(`\n${chosen.length - survived.length}/${chosen.length} mutaties gevangen`);
if (survived.length) {
  console.log('Overleefd (een regel zonder test die hem bewaakt):');
  for (const s of survived) console.log(`  - ${s}`);
  process.exit(1);
}
